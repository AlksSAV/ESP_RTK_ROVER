# Embeds web/rtk-monitor.html into src/web_dashboard.h as a PROGMEM string.
#
# Runs as a PlatformIO extra script (see platformio.ini), before every build.
# Regenerates only when the HTML is newer than the header, so incremental
# builds stay untouched.

import os

Import("env")

ROOT = env.subst("$PROJECT_DIR")
HTML = os.path.join(ROOT, "web", "rtk-monitor.html")
HEADER = os.path.join(ROOT, "src", "web_dashboard.h")


def chunked_hex(data, per_line=32):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        body = "".join("\\x%02x" % b for b in chunk)
        lines.append('    "%s"' % body)
    return "\n".join(lines)


def embed(target, source, env):
    with open(HTML, "rb") as f:
        data = f.read()

    out = (
        "// GENERATED by tools/embed_html.py from web/rtk-monitor.html.\n"
        "// Do not edit - edit the HTML and rebuild.\n\n"
        "#pragma once\n\n"
        "#include <pgmspace.h>\n\n"
        "static const char RTK_DASHBOARD[] PROGMEM =\n"
        + chunked_hex(data)
        + ";\n"
    )

    old = None
    if os.path.exists(HEADER):
        with open(HEADER, "r", encoding="utf-8") as f:
            old = f.read()
    if old != out:
        with open(HEADER, "w", encoding="utf-8") as f:
            f.write(out)
        print("embed_html: %s -> %s (%d bytes)" % (HTML, HEADER, len(data)))


if os.path.exists(HTML):
    # A real builder node, so 'ninja' also rebuilds when the HTML changes.
    env.Depends("$BUILD_DIR/src/link_wifi.cpp", HTML)
    embed(None, None, env)
else:
    print("embed_html: missing %s, skipping" % HTML)
